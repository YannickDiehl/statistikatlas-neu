#!/usr/bin/env node
// Turns every .svg in a folder into a string constant in <folder>/index.ts,
// so components can inline the pictures without `?raw` imports (tests run under node).
// Ids inside each picture get the export name as prefix, so two inline pictures never clash.
// Usage: node scripts/svg-to-ts.mjs src/chapter/companions
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, basename, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const exportName = file => basename(file)
  .replace(/\.svg$/, '')
  .replace(/[^A-Za-z0-9]+(.)/g, (_, c) => c.toUpperCase())
  .replace(/^[^A-Za-z_$]/, m => `_${m}`);

export const clean = svg => svg
  .replace(/<\?xml[^>]*\?>/g, '')
  .replace(/<!DOCTYPE[^>]*>/gi, '')
  .replace(/<!--[^]*?-->/g, '')
  .trim();

/** Prefixes id="x", url(#x), href="#x" and xlink:href="#x" with `${prefix}-`. */
export const prefixIds = (svg, prefix) => svg
  .replace(/(\sid=")([^"]+")/g, `$1${prefix}-$2`)
  .replace(/url\(#([^)]+)\)/g, `url(#${prefix}-$1)`)
  .replace(/((?:\s|xlink:)href=")#([^"]+")/g, `$1#${prefix}-$2`);

export function svgToTs(dir) {
  const files = readdirSync(dir).filter(f => f.endsWith('.svg')).sort();
  const lines = [
    '// Generated by scripts/svg-to-ts.mjs from the .svg files in this folder. Do not edit by hand.',
    ...files.map(f => {
      const name = exportName(f);
      return `export const ${name} = ${JSON.stringify(prefixIds(clean(readFileSync(join(dir, f), 'utf8')), name))};`;
    }),
    '',
  ];
  writeFileSync(join(dir, 'index.ts'), lines.join('\n'));
  return files.length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('Usage: node scripts/svg-to-ts.mjs <folder>');
    process.exit(1);
  }
  console.log(`${join(dir, 'index.ts')}: ${svgToTs(dir)} svg`);
}
